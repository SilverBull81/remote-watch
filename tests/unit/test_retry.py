import pytest

from remote_watch import RetryPolicy
from remote_watch.notifications._retry import retry_delay

#******************************************************************************************************************
# ТЕСТЫ
#******************************************************************************************************************


#------------------------------------------------------------------------------------------------------------------
# ТЕСТ : Рост задержки, случайная доля и верхний предел
#------------------------------------------------------------------------------------------------------------------
@pytest.mark.parametrize(("attempt", "upper"), [(1, 1.0), (2, 2.0), (3, 3.0), (40, 3.0), (10**100, 3.0)])
@pytest.mark.parametrize("fraction", [0.0, 0.5, 1.0])
def test_full_jitter(
    attempt: int,
    upper: float,
    fraction: float,
    ) -> None:

    """Apply exponential full jitter without exceeding the local cap.

    :param attempt: Failed attempt number.
    :type attempt: int

    :param upper: Expected jitter upper bound.
    :type upper: float

    :param fraction: Deterministic random fraction.
    :type fraction: float
    """

    # attempt, upper, fraction - номер попытки, верхняя граница и доля выбранной задержки.

    policy = RetryPolicy(backoff_cap=3.0)
    assert retry_delay(policy, attempt, None, fraction) == upper * fraction
    assert retry_delay(policy, attempt, 9.0, fraction) == 9.0
#------------------------------------------------------------------------------------------------------------------


#------------------------------------------------------------------------------------------------------------------
# ТЕСТ : Отклонение неверного результата генератора случайных чисел
#------------------------------------------------------------------------------------------------------------------
@pytest.mark.parametrize("fraction", [-1, 2, True, float("nan"), float("inf")])
def test_invalid_random_value(
    fraction: object,
    ) -> None:

    """Reject malformed injected randomness instead of creating an unbounded delay.

    :param fraction: Invalid random-source value.
    :type fraction: object
    """

    # fraction - результат ошибочного пользовательского источника случайных чисел.

    with pytest.raises((ValueError, TypeError)):
        retry_delay(RetryPolicy(), 1, None, fraction)
#------------------------------------------------------------------------------------------------------------------


#------------------------------------------------------------------------------------------------------------------
# ТЕСТ : Большие номера попыток и крайние значения float без переполнения
#------------------------------------------------------------------------------------------------------------------
def test_extreme_backoff() -> None:

    """Handle finite float extremes without overflowing a ratio or integer power."""

    policy = RetryPolicy(backoff_base=5e-324, backoff_cap=1e308)
    assert retry_delay(policy, 1, None, 1.0) == 5e-324
    assert retry_delay(policy, 10**100, None, 1.0) == 1e308

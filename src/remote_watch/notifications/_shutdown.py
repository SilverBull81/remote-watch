#
# Функции:
# -> register(): Добавление runtime в реестр активных объектов.
# -> unregister(): Удаление завершившегося runtime из реестра.
# -> shutdown(): Остановка всех runtime с общим сроком ожидания.


#******************************************************************************************************************
# ИМПОРТ
#******************************************************************************************************************
from __future__ import annotations

import atexit
import threading
import time
import weakref
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from remote_watch.notifications.runtime import NotificationRuntime


_runtimes: weakref.WeakSet[NotificationRuntime] = weakref.WeakSet()
_lock = threading.Lock()


#******************************************************************************************************************
# ФУНКЦИИ
#******************************************************************************************************************


#------------------------------------------------------------------------------------------------------------------
# ФУНКЦИЯ : Добавление runtime в реестр активных объектов
#------------------------------------------------------------------------------------------------------------------
def register(
    runtime: NotificationRuntime,
) -> None:

    """Track a started runtime without extending its lifetime.

    :param runtime: Runtime being started.
    :type runtime: NotificationRuntime
    """

    # runtime - владелец рабочего потока; слабая ссылка не удерживает закрытые объекты.

    with _lock:
        _runtimes.add(runtime)
#------------------------------------------------------------------------------------------------------------------


#------------------------------------------------------------------------------------------------------------------
# ФУНКЦИЯ : Удаление завершившегося runtime из реестра
#------------------------------------------------------------------------------------------------------------------
def unregister(
    runtime: NotificationRuntime,
) -> None:

    """Forget a finished runtime.

    :param runtime: Runtime whose worker has finished.
    :type runtime: NotificationRuntime
    """

    # runtime - завершившийся владелец потока.

    with _lock:
        _runtimes.discard(runtime)
#------------------------------------------------------------------------------------------------------------------


#------------------------------------------------------------------------------------------------------------------
# ФУНКЦИЯ : Остановка всех runtime с общим сроком ожидания
#------------------------------------------------------------------------------------------------------------------
def shutdown() -> None:

    """Best-effort process-exit cleanup with one shared one-second wait budget."""

    # При аварийном завершении процесса atexit не гарантирован; основным остаётся явный stop.
    # Один общий срок не умножается на число активных runtime.
    deadline = time.monotonic() + 1.0

    with _lock:
        runtimes = tuple(_runtimes)

    for runtime in runtimes:
        runtime._request_stop(deadline=deadline)

    for runtime in runtimes:
        thread = runtime._thread

        if thread is not None and thread.ident is not None and thread is not threading.current_thread():
            thread.join(max(0.0, deadline - time.monotonic()))
#------------------------------------------------------------------------------------------------------------------


atexit.register(shutdown)



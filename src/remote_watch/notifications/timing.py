# КЛАСС : Системные монотонные часы и ожидания asyncio
#------------------------------------------------------------------------------------------------------------------
class SystemDeliveryClock:
    """Use system monotonic time and asyncio for production delivery scheduling."""

    #--------------------------------------------------------------------------------------------------------------
    # ИНТЕРФЕЙС : Чтение монотонного времени доставки
    #--------------------------------------------------------------------------------------------------------------
    def monotonic(self) -> float:

        """Read the system monotonic clock.

        :return: Monotonic time in seconds.
        :rtype: float
        """

        return time.monotonic()
    #--------------------------------------------------------------------------------------------------------------

    #--------------------------------------------------------------------------------------------------------------
    # ИНТЕРФЕЙС : Отменяемое ожидание перед повторной попыткой
    #--------------------------------------------------------------------------------------------------------------
    async def sleep(
        self,
        delay: float,
        ) -> None:

        """Yield the loop for a cancellable retry delay.

        :param delay: Nonnegative delay in seconds.
        :type delay: float
        """

        # delay - ожидание, во время которого остальные получатели продолжают работать.

        await asyncio.sleep(delay)
    #--------------------------------------------------------------------------------------------------------------
